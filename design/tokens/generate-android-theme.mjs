import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(path.join(dir, "tokens.json"), "utf8"));
const scheme = JSON.parse(
  readFileSync(path.join(dir, "generated", "color-scheme.json"), "utf8")
);

const themeDir = path.join(
  dir,
  "..",
  "..",
  "apps",
  "mobile",
  "android",
  "src",
  "main",
  "kotlin",
  "in",
  "chetna",
  "mobile",
  "ui",
  "theme"
);

const header = `// Generated by design/tokens/generate-android-theme.mjs from design/tokens/tokens.json
// and design/tokens/generated/color-scheme.json — do not hand-edit, re-run the generator instead.
`;

function hexToComposeColor(hex) {
  return `Color(0xFF${hex.replace("#", "").toUpperCase()})`;
}

// M3's ColorScheme constructor doesn't accept every role we generate into
// color-scheme.json — "shadow" was dropped from the Compose Material3 API
// (elevation-based tonal overlays replaced it), confirmed empirically via a
// compile error, not assumed from docs.
const UNSUPPORTED_COMPOSE_ROLES = ["shadow"];

function colorSchemeBlock(roles, functionName) {
  const lines = Object.entries(roles)
    .filter(([role]) => !UNSUPPORTED_COMPOSE_ROLES.includes(role))
    .map(([role, hex]) => `        ${role} = ${hexToComposeColor(hex)},`)
    .join("\n");
  return `fun ${functionName}(): ColorScheme {
    return ${functionName === "chetnaLightColorScheme" ? "lightColorScheme" : "darkColorScheme"}(
${lines}
    )
}`;
}

const colorKt = `${header}
package \`in\`.chetna.mobile.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

${colorSchemeBlock(scheme.light, "chetnaLightColorScheme")}

${colorSchemeBlock(scheme.dark, "chetnaDarkColorScheme")}
`;

const radii = tokens.shape.radius;
const shapeKt = `${header}
package \`in\`.chetna.mobile.ui.theme

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.dp

val BezelShape = RoundedCornerShape(${radii.bezel}.dp)
val CardShape = RoundedCornerShape(${radii.card}.dp)
val ButtonShape = RoundedCornerShape(${radii.button}.dp)
val RowShape = RoundedCornerShape(${radii.row}.dp)
`;

mkdirSync(themeDir, { recursive: true });
writeFileSync(path.join(themeDir, "Color.kt"), colorKt);
writeFileSync(path.join(themeDir, "Shape.kt"), shapeKt);

console.log(`Wrote ${path.join(themeDir, "Color.kt")}`);
console.log(`Wrote ${path.join(themeDir, "Shape.kt")}`);
